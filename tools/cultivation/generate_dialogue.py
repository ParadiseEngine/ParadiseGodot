def compose(sentences, attrs):
    out = []
    for i, (s, a) in enumerate(itertools.product(sentences, attrs)):
        if i % 2 == 0:
            out.append("{npc}" + a + "：“" + s + "”")
        else:
            out.append("“" + s + "”{npc}" + a + "。")
    return out

def dedupe(lines):
    seen, out = set(), []
    for line in lines:
        if line not in seen:
            seen.add(line)
            out.append(line)
    return out

