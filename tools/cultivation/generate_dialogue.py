def build():
    dialogue = json.load(open(ROOT / "dialogue.json"))
    hand = {b["minAffection"]: b["replies"] for b in dialogue["buckets"]}

    def bucket(min_aff, sentences, attrs, hand_key):
        return {"minAffection": min_aff,
                "replies": dedupe(hand.get(hand_key, []) + compose(sentences, attrs))}

    dialogue["buckets"] = [
        bucket(-500, HOSTILE_SENT, HOSTILE_ATTR, -500),
        bucket(-99, STRANGER_SENT, NEUTRAL_ATTR, -99),
        bucket(100, ACQ_SENT, WARM_ATTR, 100),
        bucket(300, FRIEND_SENT, WARM_ATTR[:4] + CLOSE_ATTR[:4], 300),
        bucket(500, CONFIDANT_SENT, CLOSE_ATTR, 500),
    ]
    dialogue["keywordReplies"] = [
        {"keywords": kw, "replies": dedupe(hand_lines + compose(sent, attrs))}
        for kw, hand_lines, sent, attrs in KEYWORDS
    ]
    dialogue["personalityReplies"] = [
        {"personality": name, "replies": dedupe(hand_lines + compose(sent, attrs))}
        for name, (attrs, hand_lines, sent) in PERSONALITIES.items()
    ]
    json.dump(dialogue, open(ROOT / "dialogue.json", "w"), indent=2, ensure_ascii=False)

    text = json.load(open(ROOT / "text.json"))
    text["messages"]["exploreNothing"] = dedupe(EXPLORE_NOTHING)
    text["messages"]["exploreHerbs"] = dedupe(EXPLORE_HERBS)
    text["messages"]["exploreStones"] = dedupe(EXPLORE_STONES)
    text["messages"]["exploreInsight"] = dedupe(EXPLORE_INSIGHT)
    json.dump(text, open(ROOT / "text.json", "w"), indent=2, ensure_ascii=False)

    counts = {
        "buckets": sum(len(b["replies"]) for b in dialogue["buckets"]),
        "keywords": sum(len(k["replies"]) for k in dialogue["keywordReplies"]),
        "personalities": sum(len(p["replies"]) for p in dialogue["personalityReplies"]),
        "explore": sum(len(text["messages"][k]) for k in
                       ("exploreNothing", "exploreHerbs", "exploreStones", "exploreInsight")),
    }
    counts["total"] = sum(counts.values())
    print(counts)

if __name__ == "__main__":
    build()
